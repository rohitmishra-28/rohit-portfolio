// Converts the source images in src/assets/figma (design exports) and
// src/assets/uploads (added through the CMS) into responsive AVIF/WebP files
// in public/images, and writes a typed manifest for <Picture>. The file name
// without its extension is the image's name in the content files.
//
// Runs before `next dev` and `next build` (see package.json), so an image
// uploaded through the CMS is built by the deploy workflow. Unchanged
// sources are skipped by content hash, which also holds on CI checkouts
// where file times say nothing.
import { createHash } from "node:crypto";
import { access, mkdir, readdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import sharp from "sharp";

const root = path.resolve(import.meta.dirname, "..");
const srcDirs = ["src/assets/figma", "src/assets/uploads"].map((d) => path.join(root, d));
const outDir = path.join(root, "public/images");
const hashesPath = path.join(root, "src/assets/image-hashes.json");
const manifestPath = path.join(root, "src/lib/images.generated.ts");

const TARGET_WIDTHS = [480, 800, 1200, 1600, 1920];
const SMALL_WIDTHS = [76, 152]; // emblems are rendered at 76px
const SOURCE = /\.(png|jpe?g|webp)$/i;

const exists = (file) => access(file).then(() => true, () => false);
const readJson = (file) => readFile(file, "utf8").then(JSON.parse, () => ({}));

await mkdir(outDir, { recursive: true });
const hashes = await readJson(hashesPath);
const manifest = {};

const sources = [];
for (const dir of srcDirs) {
  const files = await readdir(dir).catch(() => []);
  for (const file of files.filter((f) => SOURCE.test(f))) {
    const name = path.basename(file, path.extname(file));
    if (sources.some((s) => s.name === name)) {
      throw new Error(`Two source images are both named "${name}". Rename one of them.`);
    }
    sources.push({ name, input: path.join(dir, file) });
  }
}
sources.sort((a, b) => a.name.localeCompare(b.name));

for (const { name, input } of sources) {
  const buffer = await readFile(input);
  const hash = createHash("sha1").update(buffer).digest("hex");
  // Apply EXIF orientation so phone photos aren't sideways.
  const image = () => sharp(buffer).rotate();
  const { width, height } = await image().toBuffer({ resolveWithObject: true }).then((r) => r.info);

  const candidates = width <= 200 ? SMALL_WIDTHS : TARGET_WIDTHS;
  const widths = [...new Set([...candidates.filter((w) => w < width), width])];
  const outputs = widths.flatMap((w) => ["avif", "webp"].map((ext) => path.join(outDir, `${name}-${w}.${ext}`)));
  const fresh = hashes[name] === hash && (await Promise.all(outputs.map(exists))).every(Boolean);

  if (!fresh) {
    for (const w of widths) {
      const resized = () => image().resize({ width: w });
      await resized().avif({ quality: 50 }).toFile(path.join(outDir, `${name}-${w}.avif`));
      await resized().webp({ quality: 74 }).toFile(path.join(outDir, `${name}-${w}.webp`));
    }
    hashes[name] = hash;
  }

  manifest[name] = { width, height, widths };
  console.log(`${name}: ${width}x${height} -> ${widths.join(", ")}${fresh ? " (unchanged)" : ""}`);
}

for (const name of Object.keys(hashes)) if (!(name in manifest)) delete hashes[name];
await writeFile(hashesPath, `${JSON.stringify(hashes, null, 2)}\n`);

const body = `// Generated by scripts/optimize-images.mjs — do not edit by hand.
export const images = ${JSON.stringify(manifest, null, 2)} as const;

export type ImageName = keyof typeof images;
`;
const previous = await readFile(manifestPath, "utf8").catch(() => "");
if (previous !== body) await writeFile(manifestPath, body);
