// Converts the Figma exports in src/assets/figma into responsive AVIF/WebP
// files in public/images and writes a typed manifest for <Picture>.
// Run with `npm run images` after adding or replacing a source PNG.
import { mkdir, readdir, stat, writeFile } from "node:fs/promises";
import path from "node:path";
import sharp from "sharp";

const root = path.resolve(import.meta.dirname, "..");
const srcDir = path.join(root, "src/assets/figma");
const outDir = path.join(root, "public/images");
const manifestPath = path.join(root, "src/lib/images.generated.ts");

const TARGET_WIDTHS = [480, 800, 1200, 1600, 1920];
const SMALL_WIDTHS = [76, 152]; // emblems are rendered at 76px

async function isFresh(output, sourceMtime) {
  try {
    return (await stat(output)).mtimeMs >= sourceMtime;
  } catch {
    return false;
  }
}

await mkdir(outDir, { recursive: true });
const files = (await readdir(srcDir)).filter((f) => f.endsWith(".png")).sort();
const manifest = {};

for (const file of files) {
  const name = path.basename(file, ".png");
  const input = path.join(srcDir, file);
  const { mtimeMs } = await stat(input);
  const { width, height } = await sharp(input).metadata();

  const candidates = width <= 200 ? SMALL_WIDTHS : TARGET_WIDTHS;
  const widths = [...new Set([...candidates.filter((w) => w < width), width])];

  for (const w of widths) {
    const resized = () => sharp(input).resize({ width: w });
    const avif = path.join(outDir, `${name}-${w}.avif`);
    const webp = path.join(outDir, `${name}-${w}.webp`);
    if (!(await isFresh(avif, mtimeMs))) await resized().avif({ quality: 50 }).toFile(avif);
    if (!(await isFresh(webp, mtimeMs))) await resized().webp({ quality: 74 }).toFile(webp);
  }

  manifest[name] = { width, height, widths };
  console.log(`${name}: ${width}x${height} -> ${widths.join(", ")}`);
}

const body = `// Generated by scripts/optimize-images.mjs — do not edit by hand.
export const images = ${JSON.stringify(manifest, null, 2)} as const;

export type ImageName = keyof typeof images;
`;
await writeFile(manifestPath, body);
